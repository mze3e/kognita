"""Generate AIRG_MAP.md: every row of the MAS AI Risk Management table in docs/control-frameworks.md
mapped to the PWM terms that cite that paragraph, or to its boundary or out-of-scope disposition.

    python3 tools/gen_airg_map.py [--check]
"""
import pathlib, re, sys
from rdflib import Graph, URIRef, RDFS
BASE = pathlib.Path(__file__).resolve().parents[1]
PWM = "https://ahmedmuzammil.com/ontology/pwm#"
SRC = BASE.parents[1] / "control-frameworks.md"

def expand(text):
    """Paragraph keys named by a paragraph column or a citation locator: '4.5', 'fn25'."""
    keys = set()
    for m in re.finditer(r"(\d+)\.(\d+)(?:\([a-z]\))*\s*(?:to|-)\s*(?:(\d+)\.)?(\d+)", text):
        sec, a, sec2, b = m.group(1), int(m.group(2)), m.group(3), int(m.group(4))
        if sec2 in (None, sec):
            keys |= {f"{sec}.{n}" for n in range(a, b + 1)}
    for m in re.finditer(r"(?<![\d.])(\d+\.\d+)", text):
        keys.add(m.group(1))
    for m in re.finditer(r"fn\s*(\d+)", text):
        keys.add("fn" + m.group(1))
    return keys

def rows():
    text = SRC.read_text()
    start = text.index("## VII. MAS Guidelines on AI Risk Management")
    end = text.index("### Gaps Found by This Audit", start)
    for line in text[start:end].splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and re.match(r"\d+\.\d+", cells[0]) and cells[0][0] in "23456":
            yield cells[0], cells[1], cells[2], cells[3] if len(cells) > 3 else ""

def terms_by_paragraph(ont):
    out = {}
    cites, locator = URIRef(PWM + "cites"), URIRef(PWM + "locator")
    citation = URIRef(PWM + "citation")
    for term, c in ont.subject_objects(citation):
        if not str(term).startswith(PWM) or ont.value(c, cites) != URIRef(PWM + "ref-MAS-AIRG"):
            continue
        for key in expand(str(ont.value(c, locator))):
            out.setdefault(key, set()).add(str(term)[len(PWM):])
    return out

def build():
    ont = Graph().parse(BASE / "pwm.ttl")
    by_para = terms_by_paragraph(ont)
    lines, covered, boundary, open_ = [], 0, 0, []
    table = []
    for para, expectation, status, _kog in rows():
        keys = expand(para)
        terms = sorted(set().union(*(by_para.get(k, set()) for k in keys)) if keys else set())
        if terms:
            disposition = "mapped"; covered += 1
        elif status in ("Boundary", "Out of scope"):
            disposition = status.lower() + " (control-frameworks.md)"; boundary += 1
        else:
            disposition = "no PWM term cites this paragraph yet"; open_.append(para)
        shown = ", ".join(f"`{t}`" for t in terms[:6]) + (f" and {len(terms) - 6} more" if len(terms) > 6 else "")
        table.append(f"| {para} | {expectation.replace('|', '/')[:110]} | {status} | {shown or 'none'} | {disposition} |")
    head = ["# MAS AIRG paragraph map", "",
            "Generated by `tools/gen_airg_map.py` from the MAS table in [docs/control-frameworks.md](../../control-frameworks.md) and the citations in `pwm.ttl`. Do not edit.", "",
            f"Of {len(table)} paragraph rows in Sections 2 to 6, **{covered}** are mapped to PWM terms that cite them, **{boundary}** are marked boundary or out of scope in control-frameworks.md, and **{len(open_)}** have no PWM term yet.", "",
            "A term is mapped to a paragraph when one of its citations to the MAS AIRG register entry names that paragraph (ranges such as 4.5 to 4.13 count each paragraph; a sub-paragraph letter is read as its paragraph). The map covers the paragraphs that control-frameworks.md lists; it is only as complete as that table. A mapped paragraph shows that PWM records the data the paragraph points to, not that a firm meets the paragraph. Citations to the MAS AIRG register entry are instrument-level.", ""]
    if open_:
        head += ["Paragraphs with no PWM term yet: " + ", ".join(open_) + ".", ""]
    head += ["| Para | Expectation | Kognita status | PWM terms | Disposition |", "|---|---|---|---|---|"]
    return "\n".join(head + table) + "\n", covered, boundary, open_

if __name__ == "__main__":
    text, covered, boundary, open_ = build()
    target = BASE / "AIRG_MAP.md"
    if "--check" in sys.argv:
        sys.exit(0 if target.read_text() == text else 1)
    target.write_text(text)
    print(f"mapped {covered}, boundary or out of scope {boundary}, open {len(open_)}: {open_}")
